dofile("tests/helpers.lua")
local model = addon_script("field_medical_model")
local config = read_settings().blood

local one = model.new(config, 1)
assert(not one:penetrating_hit(0.8, "stopped"))
assert(not one:penetrating_hit(0.8, "unknown"))
assert(not one:penetrating_hit(0, "penetrated"))
assert(one:penetrating_hit(0.1, "penetrated"))
near(one.blood, 1)
local rate = one:bleeding_rate()
assert(one:penetrating_hit(0.25, "penetrated"))
local combined = one:bleeding_rate()
assert(combined > 2 * rate)
one:tick(16)
near(one.blood, 1 - combined * 16)
local blood = one.blood
assert(one:bandage() == 1 and one.wounds[2].treatment == "bandaged")
assert(one:bleeding_rate() > 0 and one:bleeding_rate() < combined)
assert(one.blood == blood)
assert(one:bandage() == 1)
assert(one:bandage() == 0)
assert(one:medkit(7) == 2 and one:bleeding_rate() == 0 and #one.wounds == 2)
assert(one.blood == blood)
one:tick(178)
assert(one:medkit() == 0)
local snapshot = one:snapshot()
local copy = model.new(config, 0.01, snapshot)
local copy2 = model.new(config, 1, copy:snapshot())
near(copy2.blood, blood)
assert(copy2.wounds[2].stable_seconds == config.stabilization_seconds - 178)
snapshot.wounds[1].severity = 0
assert(copy2.wounds[1].severity > 0)
copy2:tick(121)
assert(copy2:bleeding_rate() == 0)
copy2:tick(1)
assert(copy2:bleeding_rate() == combined)
assert(copy2.wounds[2].treatment == "open" and copy2.wounds[2].needs_dressing)
assert(copy2:medkit() == 0)
copy2:tick(7)
near(copy2.blood, blood - combined * 7)
assert(copy2:bandage() == 1)
assert(copy2:medkit(4) == 1 and copy2.wounds[2].treatment == "stable")
assert(copy2.wounds[1].treatment == "open")
local before_doctor = copy2.blood
assert(copy2:doctor() == 2)
near(copy2.blood, before_doctor)
assert(copy2:bleeding_rate() == 0 and #copy2.wounds == 0)

local nourished, deprived = model.new(config, 0.5), model.new(config, 0.5)
near(nourished:sleep(2, 1, 1), 2 * config.rest_blood_per_hour)
assert(deprived:sleep(2, 0, 0) < nourished.blood - 0.5)
assert(nourished.blood > deprived.blood and deprived.blood > 0.5)

local rest = model.new(config, 0.85)
rest:penetrating_hit(0.035, "penetrated")
rest:medkit()
rest:sleep(3, 1, 1)
near(rest.blood, config.recovery_cap_with_wounds)
assert(rest.wounds[1].stable_seconds == 120)
local sleep_bleeding = model.new(config, 0.85)
sleep_bleeding:penetrating_hit(0.035, "penetrated")
local light_rate = sleep_bleeding:bleeding_rate()
sleep_bleeding:medkit()
sleep_bleeding:sleep(6, 1, 1)
near(sleep_bleeding.blood, config.recovery_cap_with_wounds - light_rate * 60)
assert(sleep_bleeding.wounds[1].needs_dressing)
rest:doctor()
rest:sleep(4, 1, 1)
near(rest.blood, 1)

local systemic = model.new(config, 1)
systemic:observe_health(0.4)
systemic:observe_health(0.62)
near(systemic.blood, 0.4)
assert(#systemic.wounds == 0)
local effects = systemic:effects()
assert(effects.stamina < 1 and effects.movement < 1 and effects.recoil > 1 and effects.vision > 0)
systemic:observe_health(0.12)
systemic:tick(0.1)
assert(systemic:effects().unconscious)
local downed = model.new(config, 1, systemic:snapshot())
assert(downed:effects().unconscious)
downed:tick(config.faint_seconds + 0.1)
assert(not downed:effects().unconscious)
downed:penetrating_hit(2, "penetrated")
downed:tick(20)
near(downed.blood, 0)
assert(downed:sleep(10, 1, 1) == 0)
