dofile("tests/helpers.lua")
local blood_model = addon_script("field_medical_model")
local device = addon_script("field_medical_tourniquet")
local config = read_settings().blood

local blood = blood_model.new(config, 0.75)
local bands = device.new()
assert(not bands:can_apply("ribs", blood.blood))
assert(not bands:can_apply("head", blood.blood))
assert(not bands:can_apply("left_leg", 0))
assert(blood:add_wound(1, "left_leg"))
assert(blood:add_wound(0.1, "right_leg"))
local total_bleed = blood:bleeding_rate()
local cost = assert(bands:apply("left_leg", blood.blood))
near(cost, .75 * .14)
near(blood:deduct_blood(cost), cost)
near(blood.blood, .75 * .86)
assert(not bands:can_apply("left_leg", blood.blood))
assert(bands:can_remove("left_leg"))
local uncovered = blood:bleeding_rate(bands)
assert(uncovered > 0 and uncovered < total_bleed)

local completed, used = blood:medkit(2)
assert(completed == 0 and used == 2 and blood.wounds[1].treatment == "open")
local saved = blood:snapshot()
blood = blood_model.new(config, 1, saved)
assert(blood.wounds[1].part == "left_leg" and blood.wounds[1].stabilization_progress == 2)
assert(blood:medkit(2) == 1 and blood.wounds[1].treatment == "stable")
near(blood.blood, .75 * .86)
assert(bands:remove("left_leg"))
near(blood:bleeding_rate(bands), uncovered)
assert(bands:effects().sprint_block and bands:effects().movement < 1 and bands:effects().limp_side == "left")
assert(not bands:can_apply("left_leg", blood.blood))

assert(blood:epinephrine(12))
assert(blood:effects().movement == 1 and bands:effects().movement < 1)
blood = blood_model.new(config, 1, blood:snapshot())
assert(blood.epinephrine_seconds == 12)
blood:tick(12, bands)
assert(blood.epinephrine_seconds == 0 and blood:effects().movement < 1)
assert(bands:doctor() == 1 and bands:can_apply("left_leg", blood.blood))
assert(bands:effects().movement == 1 and not bands:effects().sprint_block)

local severe = blood_model.new(config, .6)
assert(severe:add_wound(1, "right_arm"))
local count, spent = severe:medkit(4)
assert(count == 1 and spent == 4 and severe:bleeding_rate() == 0)
near(severe.blood, .6)

local settings = {duration_seconds = 10, arm_integrity_loss_per_second = .07}
blood = blood_model.new(config, 1)
bands = device.new(settings)
assert(blood:add_wound(.25, "left_arm"))
local rate = blood:bleeding_rate()
blood:deduct_blood(assert(bands:apply("left_arm", blood.blood)))
local previous = bands:effects().reload
blood:tick(8, bands)
near(blood.blood, .92)
assert(bands:effects().reload < previous and bands:status()[1].integrity < 1)
bands = device.new(settings, bands:snapshot())
near(bands:next_expiry(), 2)
blood:tick(5, bands)
near(blood.blood, .92 - 3 * rate)
assert(not bands:blocks("left_arm") and not bands:can_remove("left_arm"))
assert(not bands:can_apply("left_arm", blood.blood))
near(bands:effects().reload, .49)
assert(bands:effects().sway > 1)

local manual = device.new(settings)
assert(manual:apply("left_arm", blood.blood))
near(blood:bleeding_rate(manual), 0)
assert(manual:remove("left_arm"))
near(blood:bleeding_rate(manual), rate)
assert(not manual:remove("left_arm"))
assert(not manual:can_apply("left_arm", blood.blood))

local sleep = blood_model.new(config, .85)
local sleeper = device.new(settings)
assert(sleep:add_wound(.25, "left_arm"))
sleep:deduct_blood(assert(sleeper:apply("left_arm", sleep.blood)))
sleep:sleep(1, 1, 1, sleeper)
near(sleep.blood, .85 * .92 + config.rest_blood_per_hour * 10 / config.sleep_bleed_seconds_per_hour
    - rate * (config.sleep_bleed_seconds_per_hour - 10))
assert(not sleeper:can_apply("left_arm", sleep.blood))
assert(sleeper:effects().reload < 1)
